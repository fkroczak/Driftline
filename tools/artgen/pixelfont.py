def width(text, spacing=1):
    return sum(len(G[c][0]) + spacing for c in text) - spacing if text else 0


def draw(img, x, y, text, color, shadow=None, spacing=1):
    """Schreibt `text` mit Oberkante bei y. `shadow`: Farbe der 1-px-Kante unten rechts."""
    px = img.load()
    for layer in ((1, shadow), (0, color)) if shadow else ((0, color),):
        off, col = layer
        cx = x
        for ch in text:
            rows = G[ch]
            for dy, row in enumerate(rows):
                for dx, c in enumerate(row):
                    if c == "X":
                        tx, ty = cx + dx + off, y + dy + off
                        if 0 <= tx < img.width and 0 <= ty < img.height:
                            px[tx, ty] = col
            cx += len(rows[0]) + spacing
    return width(text, spacing)
